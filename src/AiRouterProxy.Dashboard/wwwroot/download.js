// Admin dashboard: client-side file download helper (used by the Settings export).
// Kept tiny and standalone - no framework, no dependencies.
window.airproxyDownload = function (fileName, text) {
    const blob = new Blob([text], { type: "application/json;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 4000);
};
